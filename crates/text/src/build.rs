use std::sync::OnceLock;

use skia_safe::{Codec, Data, FontMgr};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BuildInfo {
    pub freetype: bool,
    pub skia_milestone: u32,
    pub jpeg_decode: bool,
    pub webp_decode: bool,
}

/// What the linked Skia build supports, probed once at runtime.
pub fn build_info() -> BuildInfo {
    static INFO: OnceLock<BuildInfo> = OnceLock::new();
    *INFO.get_or_init(|| BuildInfo {
        freetype: FontMgr::custom_empty().is_some(),
        skia_milestone: skia_safe::MILESTONE as u32,
        jpeg_decode: decodes(TINY_JPEG),
        webp_decode: decodes(TINY_WEBP),
    })
}

fn decodes(bytes: &'static [u8]) -> bool {
    Codec::from_data(Data::new_copy(bytes)).is_some()
}

